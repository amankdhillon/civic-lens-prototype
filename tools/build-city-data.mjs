// Builds the shell's data and the database seed from data/city/structure.json.
//   js/shell/city-data.js  (loaded by the shell: DIST, BODIES, MEETINGS, DATA_NOTICE)
//   supabase/seed-shell.sql (run after migration-6.sql; "on conflict do nothing", safe to re-run)
// Run from the project root:  node tools/build-city-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

const s = JSON.parse(readFileSync('data/city/structure.json', 'utf8'));

// ---- 1. shell data file ----
// Bodies with districts list their members (the district representative), unless they have a roster.
for (const [id, b] of Object.entries(s.bodies)) {
  const linked = Object.keys(s.districts).filter(p => s.districts[p].body === id);
  if (linked.length) b.members = linked;
}
const js = [
  '// Generated by tools/build-city-data.mjs from data/city/structure.json. Do not edit by hand.',
  `const DATA_NOTICE=${JSON.stringify(s.notice)};`,
  `const DATA_CHECKED=${JSON.stringify(s.checked)};`,
  `const DIST=${JSON.stringify(s.districts, null, 1)};`,
  `const BODIES=${JSON.stringify(s.bodies, null, 1)};`,
  `const MEETINGS=${JSON.stringify(s.meetings.map(m => ({
    ...m, items: [], source: s.meeting_source, checked: s.checked,
  })), null, 1)};`,
  '',
].join('\n');
writeFileSync('js/shell/city-data.js', js);

// ---- 2. database seed (the shell's sample discussions come from sample-data.js) ----
const src = readFileSync('js/shell/sample-data.js', 'utf8');
const ctx = {};
vm.createContext(ctx);
const sample = vm.runInContext(`(function(){${src}\nreturn {SEED_BOARDS};})()`, ctx);
const { DIST, BODIES, MEETINGS } = JSON.parse(JSON.stringify({ DIST: s.districts, BODIES: s.bodies, MEETINGS: s.meetings }));

const q = v => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const uuid = seed => {
  const h = createHash('md5').update(seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const placeKind = id =>
  id.startsWith('fed-') ? 'congressional_district'
  : id.startsWith('state-') ? 'state_district'
  : id.startsWith('bos-') ? 'county'
  : id.startsWith('sdcc-') ? 'council_district'
  : id.startsWith('sdusd-') ? 'school_district'
  : id.startsWith('grp-') ? 'neighborhood' : null;
const toTime = t => {
  const m = /(\d{1,2}):(\d{2})\s*([ap])/i.exec(t);
  if (!m) throw new Error('Unrecognized time: ' + t);
  let h = Number(m[1]) % 12;
  if (m[3].toLowerCase() === 'p') h += 12;
  return `${String(h).padStart(2, '0')}:${m[2]}:00`;
};
// Which districts a body covers. Linked bodies use their district; city, county, and school bodies cover all their districts.
const coverage = (id, b) => {
  const linked = Object.entries(DIST).filter(([, d]) => d.body === id).map(([p]) => p);
  if (linked.length) return linked;
  const prefix = { city: 'sdcc-', county: 'bos-', school: 'sdusd-' }[b.level];
  if (prefix) return Object.keys(DIST).filter(p => p.startsWith(prefix));
  if (b.level === 'federal') return ['fed-sd'];
  if (b.level === 'state') return ['state-sd'];
  return [];
};
const at = day => `${day}T12:00:00-08:00`;

const out = [
  '-- Generated by tools/build-city-data.mjs from data/city/structure.json and js/shell/sample-data.js.',
  '-- Do not edit by hand. Run once after migration-6.sql. Safe to re-run.',
  '',
  '-- Districts',
];
for (const [id, d] of Object.entries(DIST)) {
  const kind = placeKind(id);
  if (!kind) throw new Error('No place kind for ' + id);
  out.push(`insert into places (id, kind, name) values (${q(id)}, ${q(kind)}, ${q(d.label)}) on conflict (id) do nothing;`);
}

out.push('', '-- Bodies (parents before subcommittees)');
const levelOf = { federal: 'federal', state: 'state', county: 'county', city: 'city', school: 'school', special: 'special' };
for (const [id, b] of Object.entries(BODIES)) {
  out.push(`insert into bodies (id, name, level, about, kind, parent_id) values (${q(id)}, ${q(b.name)}, ${q(levelOf[b.level])}, ${q(b.about ?? '')}, ${q(b.kind)}, ${q(b.parent ?? null)}) on conflict (id) do nothing;`);
}

out.push('', '-- Which districts each body covers (subcommittees inherit their parent\'s)');
const pairs = new Set();
for (const [id, b] of Object.entries(BODIES)) {
  for (const place of coverage(id, b)) pairs.add(id + '|' + place);
  if (b.parent) for (const place of coverage(b.parent, BODIES[b.parent])) pairs.add(id + '|' + place);
}
for (const key of pairs) {
  const [body, place] = key.split('|');
  out.push(`insert into body_places (body_id, place_id) values (${q(body)}, ${q(place)}) on conflict do nothing;`);
}

out.push('', '-- Meetings (agenda items are not in the data set yet)');
for (const m of MEETINGS) {
  out.push(`insert into meetings (id, body_id, starts_at, title) values (${q(m.id)}, ${q(m.body)}, ${q(m.date + 'T' + toTime(m.time) + '-08:00')}, ${q(m.title)}) on conflict (id) do nothing;`);
}

out.push('', '-- Sample discussions (no author account; each post keeps its sample name)');
let threadCount = 0, postCount = 0;
for (const [key, board] of Object.entries(sample.SEED_BOARDS)) {
  const i = key.indexOf(':');
  const type = key.slice(0, i), id = key.slice(i + 1);
  const scope = type === 'meet' ? 'meeting' : type;
  for (const th of board.threads) {
    const tid = uuid('thread:' + th.id);
    const first = th.posts[0];
    out.push(`insert into discussion_threads (id, scope_kind, scope_id, title, kind, author_name, created_at) values (${q(tid)}, ${q(scope)}, ${q(id)}, ${q(th.title)}, ${q(th.kind)}, ${q(first.who)}, ${q(at(first.t))}) on conflict (id) do nothing;`);
    threadCount++;
    th.posts.forEach((p, n) => {
      out.push(`insert into discussion_posts (id, thread_id, author_name, body, created_at) values (${q(uuid(`post:${th.id}:${n}`))}, ${q(tid)}, ${q(p.who)}, ${q(p.text)}, ${q(at(p.t))}) on conflict (id) do nothing;`);
      postCount++;
    });
  }
}
writeFileSync('supabase/seed-shell.sql', out.join('\n') + '\n');
console.log(`city-data.js: ${Object.keys(DIST).length} districts, ${Object.keys(BODIES).length} bodies, ${MEETINGS.length} meetings`);
console.log(`seed-shell.sql: ${pairs.size} body-district rows, ${threadCount} sample threads, ${postCount} posts`);
