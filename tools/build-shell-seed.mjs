// Builds supabase/seed-shell.sql from js/shell/sample-data.js, so the database holds the same sample
// places, bodies, meetings, items, and discussions the shell shows.
// Run from the project root after migration-6.sql:   node tools/build-shell-seed.mjs
// Safe to re-run: every row has a fixed id and uses "on conflict do nothing".
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

const src = readFileSync('js/shell/sample-data.js', 'utf8');
const ctx = {};
vm.createContext(ctx);
const data = vm.runInContext(`(function(){${src}\nreturn {DIST,BODIES,MEETINGS,SEED_BOARDS};})()`, ctx);

const q = v => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const uuid = seed => {
  const h = createHash('md5').update(seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const placeKind = id =>
  id.startsWith('fed-') ? 'congressional_district'
  : id.startsWith('state-') ? 'state_district'
  : id.startsWith('bos-') ? 'county'
  : id.startsWith('sdcc-') ? 'council_district'
  : id.startsWith('sdusd-') ? 'school_district'
  : id.startsWith('grp-') ? 'neighborhood' : null;
const bodyLevel = { fed: 'federal', state: 'state', bos: 'county', sdcc: 'city', 'sdcc-budget': 'city', sdusd: 'school' };
const toTime = t => {
  const m = /(\d{1,2}):(\d{2})\s*([ap])/i.exec(t);
  if (!m) throw new Error('Unrecognized time: ' + t);
  let h = Number(m[1]) % 12;
  if (m[3].toLowerCase() === 'p') h += 12;
  return `${String(h).padStart(2, '0')}:${m[2]}:00`;
};
const at = day => `${day}T12:00:00-08:00`; // sample times are Pacific; noon keeps the date stable

const out = [
  '-- Sample data for the shell. Generated by tools/build-shell-seed.mjs from js/shell/sample-data.js.',
  '-- Run once after migration-6.sql. Do not edit by hand; change sample-data.js and regenerate.',
  '',
  '-- Places (districts the shell can choose)',
];

for (const [id, d] of Object.entries(data.DIST)) {
  const kind = placeKind(id);
  if (!kind) throw new Error('No place kind for ' + id);
  out.push(`insert into places (id, kind, name) values (${q(id)}, ${q(kind)}, ${q(d.label)}) on conflict (id) do nothing;`);
}

out.push('', '-- Bodies (parents before subcommittees)');
for (const [id, b] of Object.entries(data.BODIES)) {
  out.push(`insert into bodies (id, name, level, about, kind, parent_id) values (${q(id)}, ${q(b.name)}, ${q(bodyLevel[id] ?? 'special')}, ${q(b.about ?? '')}, ${q(b.kind)}, ${q(b.parent ?? null)}) on conflict (id) do nothing;`);
}

out.push('', '-- Which places each body covers (subcommittees inherit their parent\'s places)');
const pairs = new Map();
for (const [place, d] of Object.entries(data.DIST)) pairs.set(d.body + '|' + place, [d.body, place]);
for (const [id, b] of Object.entries(data.BODIES)) {
  if (!b.parent) continue;
  for (const [place, d] of Object.entries(data.DIST)) {
    if (d.body === b.parent) pairs.set(id + '|' + place, [id, place]);
  }
}
for (const [body, place] of pairs.values()) {
  out.push(`insert into body_places (body_id, place_id) values (${q(body)}, ${q(place)}) on conflict do nothing;`);
}

out.push('', '-- Meetings and agenda items');
for (const m of data.MEETINGS) {
  out.push(`insert into meetings (id, body_id, starts_at, title) values (${q(m.id)}, ${q(m.body)}, ${q(m.date + 'T' + toTime(m.time) + '-08:00')}, ${q(m.title)}) on conflict (id) do nothing;`);
  for (const it of m.items) {
    const decided = !!it.result;
    const continued = decided && /^continued/i.test(it.result);
    const stage = continued ? 'continued' : decided ? 'decided' : 'introduced';
    const outcome = decided && !continued ? it.result : '';
    out.push(`insert into items (id, meeting_id, title, summary, stage, outcome) values (${q(it.id)}, ${q(m.id)}, ${q(it.title)}, ${q(it.summary ?? '')}, ${q(stage)}, ${q(outcome)}) on conflict (id) do nothing;`);
  }
}

out.push('', '-- Sample discussions (no author account; each post keeps its sample name)');
let threadCount = 0, postCount = 0;
for (const [key, board] of Object.entries(data.SEED_BOARDS)) {
  const i = key.indexOf(':');
  const type = key.slice(0, i), id = key.slice(i + 1);
  const scope = type === 'meet' ? 'meeting' : type;
  for (const th of board.threads) {
    const tid = uuid('thread:' + th.id);
    const first = th.posts[0];
    out.push(`insert into discussion_threads (id, scope_kind, scope_id, title, kind, author_name, created_at) values (${q(tid)}, ${q(scope)}, ${q(id)}, ${q(th.title)}, ${q(th.kind)}, ${q(first.who)}, ${q(at(first.t))}) on conflict (id) do nothing;`);
    threadCount++;
    th.posts.forEach((p, n) => {
      out.push(`insert into discussion_posts (id, thread_id, author_name, body, created_at) values (${q(uuid(`post:${th.id}:${n}`))}, ${q(tid)}, ${q(p.who)}, ${q(p.text)}, ${q(at(p.t))}) on conflict (id) do nothing;`);
      postCount++;
    });
  }
}

writeFileSync('supabase/seed-shell.sql', out.join('\n') + '\n');
console.log(`wrote supabase/seed-shell.sql: ${threadCount} threads, ${postCount} posts, ${pairs.size} body-place rows`);
